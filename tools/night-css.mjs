// Regenerates the `.is-style-night` token block in style.css (§6) from
// theme.json, so a Night band keeps the dark palette in every variation.
//
//   node tools/night-css.mjs          # rewrite the block in place
//   node tools/night-css.mjs --check  # exit 1 if the block is stale
//
// The block holds every palette colour whose value differs in
// styles/light.json (pinned to its theme.json value), plus every colour,
// gradient and shadow preset that references another preset. Custom
// properties resolve where they're declared, so those have to be declared
// again inside the band to pick up the pinned colours.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const theme = JSON.parse(readFileSync(join(root, 'theme.json'), 'utf8'));
const light = JSON.parse(readFileSync(join(root, 'styles/light.json'), 'utf8'));

const lightColors = Object.fromEntries(light.settings.color.palette.map(c => [c.slug, c.color]));
const refersToPreset = value => value.includes('var(--wp--preset--');
const lines = [];

for (const { slug, color } of theme.settings.color.palette) {
    if (lightColors[slug] !== color || refersToPreset(color)) {
        lines.push(`    --wp--preset--color--${slug}: ${color};`);
    }
}

for (const { slug, gradient } of theme.settings.color.gradients) {
    if (refersToPreset(gradient)) {
        lines.push(`    --wp--preset--gradient--${slug}: ${gradient};`);
    }
}

for (const { slug, shadow } of theme.settings.shadow.presets) {
    if (refersToPreset(shadow)) {
        lines.push(`    --wp--preset--shadow--${slug}: ${shadow};`);
    }
}

const start = '/* night:start (generated by tools/night-css.mjs) */';
const end = '/* night:end */';
const block = `${start}\n.is-style-night {\n${lines.join('\n')}\n}\n${end}`;

const cssPath = join(root, 'style.css');
const css = readFileSync(cssPath, 'utf8');
const from = css.indexOf(start);
const to = css.indexOf(end);

if (from === -1 || to === -1) {
    console.error('style.css has no night:start / night:end markers.');
    process.exit(1);
}

const next = css.slice(0, from) + block + css.slice(to + end.length);

if (process.argv.includes('--check')) {
    if (next !== css) {
        console.error('The Night token block in style.css is stale. Run node tools/night-css.mjs.');
        process.exit(1);
    }
    console.log('Night token block is current.');
} else {
    writeFileSync(cssPath, next);
    console.log(`Wrote ${lines.length} tokens to the Night block in style.css.`);
}
